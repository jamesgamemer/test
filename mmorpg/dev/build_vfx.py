#!/usr/bin/env python3
"""Pack generated VFX animations into sprite-sheet atlases for the game.

The effects themselves are not drawn in code: they are hand-painted-style animations generated with
Higgsfield (GPT Image 2.6, animated GIF output). The prompts are in dev/vfx_prompts.json.

    python3 dev/build_vfx.py <dir with slash_a.gif, nova.gif, scorch.png, ...>

Writes assets/vfx/<name>.webp and src/gfx/vfx-manifest.js. Needs Pillow and numpy.
"""
import json
import math
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'vfx')

# cell: size of one frame in the atlas. mask: how frame edges fade to black so nothing ends on a hard cut.
SPEC = {
    'slash_a': dict(cell=(384, 384), fps=36, mask='box'),
    'slash_b': dict(cell=(384, 384), fps=38, mask='box'),
    'slam': dict(cell=(384, 384), fps=32, mask='box'),
    'wave': dict(cell=(320, 320), fps=18, loop=True, mask='box'),
    'dash': dict(cell=(192, 384), fps=34, mask='box'),
    'nova': dict(cell=(384, 384), fps=30, mask='round'),
    'burst': dict(cell=(320, 320), fps=26, mask='box'),
    'pillar': dict(cell=(256, 512), fps=26, mask='pillar'),
    'hit': dict(cell=(192, 192), fps=30, mask='box'),
    'meteor': dict(cell=(128, 256), fps=18, loop=True, mask='box'),
    'vortex': dict(cell=(384, 384), fps=18, loop=True, mask='round'),
    'scorch': dict(cell=(512, 512), mask='round'),
    'eclipse': dict(cell=(512, 512), mask='round'),
    'ribbon': dict(cell=(1024, 256), mask='none', band=(0.22, 0.78)),
}


def edge_mask(w, h, kind):
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    u, v = (x + 0.5) / w, (y + 0.5) / h
    ramp = lambda d, a, b: np.clip((d - a) / (b - a), 0, 1)
    if kind == 'round':
        r = np.hypot(u - 0.5, v - 0.5) * 2
        m = 1 - ramp(r, 0.86, 0.99)
    elif kind == 'pillar':  # the base sits on the bottom edge and must not fade
        m = ramp(np.minimum(u, 1 - u), 0.0, 0.07) * ramp(v, 0.0, 0.05)
    elif kind == 'box':
        m = ramp(np.minimum(np.minimum(u, 1 - u), np.minimum(v, 1 - v)), 0.0, 0.06)
    else:
        m = np.ones((h, w), np.float32)
    return (m * m * (3 - 2 * m))[..., None]


def prep(im, cell, mask, band=None):
    im = im.convert('RGB')
    if band:
        im = im.crop((0, int(im.height * band[0]), im.width, int(im.height * band[1])))
    a = np.asarray(im.resize(cell, Image.LANCZOS)).astype(np.float32)
    a = np.clip((a - 9.0) * (255.0 / 246.0), 0, 255)  # crush the near-black floor to true black
    return a * mask


def main(src):
    os.makedirs(OUT, exist_ok=True)
    manifest = {}
    for name, spec in SPEC.items():
        path = next((os.path.join(src, name + e) for e in ('.gif', '.png') if os.path.exists(os.path.join(src, name + e))), None)
        if not path:
            print('missing', name)
            continue
        im = Image.open(path)
        w, h = spec['cell']
        mask = edge_mask(w, h, spec['mask'])
        frames = []
        for i in range(getattr(im, 'n_frames', 1)):
            im.seek(i)
            frames.append(prep(im, (w, h), mask, spec.get('band')))
        n = len(frames)
        if spec.get('loop') and n > 4:  # ease the last frames toward the first so the loop point does not pop
            frames[-1] = frames[-1] * 0.4 + frames[0] * 0.6
            frames[-2] = frames[-2] * 0.75 + frames[0] * 0.25
        cols = max(1, round(math.sqrt(n * h / w)))
        rows = math.ceil(n / cols)
        atlas = np.zeros((rows * h, cols * w, 3), np.float32)
        for i, f in enumerate(frames):
            atlas[(i // cols) * h:(i // cols + 1) * h, (i % cols) * w:(i % cols + 1) * w] = f
        out = os.path.join(OUT, name + '.webp')
        Image.fromarray(atlas.astype(np.uint8)).save(out, 'WEBP', quality=86, method=6)
        manifest[name] = dict(file=name + '.webp', cols=cols, rows=rows, n=n, fps=spec.get('fps', 1), loop=bool(spec.get('loop')), aspect=round(w / h, 4))
        print(f'{name:8s} {n:2d} frames  {cols}x{rows}  {atlas.shape[1]}x{atlas.shape[0]}  {os.path.getsize(out) // 1024} KB')
    with open(os.path.join(ROOT, 'src', 'gfx', 'vfx-manifest.js'), 'w') as f:
        f.write('// Generated by dev/build_vfx.py — sprite-sheet layout of each effect in assets/vfx/.\n')
        f.write('export const VFX = ' + json.dumps(manifest, indent=2) + ';\n')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '.')
